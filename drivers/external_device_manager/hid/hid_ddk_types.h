/**
 * @brief Describes basic device information, including the name, vendor ID, and product ID of an HID device. This
 * information is used as the device identifier when creating and operating an HID device.
 *
 * @since 11
 * @version 1.0
 */
typedef struct Hid_Device {
    /**
     * Device name, which can contain a maximum of 128 characters and cannot be null. If the length exceeds the upper
     * limit or the value is null, an error is returned.
     */
    const char *deviceName;
    /**
     * Vendor ID.
     */
    uint16_t vendorId;
    /**
     * Product ID.
     */
    uint16_t productId;
    /**
     * Version.
     */
    uint16_t version;
    /**
     * Bus type. For details about the value, see the bus type definition in the standard HID protocol.
     */
    uint16_t bustype;
    /**
     * Device properties. Before using this pointer, check whether it is null. This pointer is valid only when the
     * **Hid_Device** object is valid and should not be manually released.
     */
    Hid_DeviceProp *properties;
    /**
     * Number of device properties, indicating the number of valid elements in the properties array. Note: When
     * traversing the array, use this value as the boundary condition. The value may be **0**.
     */
    uint16_t propLength;
} Hid_Device;

