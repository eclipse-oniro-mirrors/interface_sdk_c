/**
 * @brief Defines the struct for the information of a HID event, including the event type, event code, and event value.
 * This struct is used to describe the events reported by an input device. In driver development scenarios, this struct
 * is used to transfer and identify events generated by various HID devices.
 *
 * @since 11
 * @version 1.0
 */
typedef struct Hid_EmitItem {
    /**
     * HID event type, which is used to identify the event type, such as key press and movement. For details, see the
     * HID protocol specifications.
     */
    uint16_t type;
    /**
     * HID event code, which is used to identify a specific HID event. For details, see the HID protocol specifications.
     */
    uint16_t code;
    /**
     * HID event value, which indicates the parameters or status of the event. The specific meaning depends on the
     * event type and code. For example, for a key press event, this parameter indicates the key status; for a movement
     * event, this parameter indicates the movement distance.
     */
    uint32_t value;
} Hid_EmitItem;

