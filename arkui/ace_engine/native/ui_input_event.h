/**
 * @brief Represents a UI input event in ArkUI. The event APIs in **ArkUI_EventModule** pass input event data to
 * callbacks through the object. You can use query APIs to obtain event information, which is suitable for
 * scenarios of recognizing or responding to user input events.
 *
 * @since 12
 */
typedef struct ArkUI_UIInputEvent ArkUI_UIInputEvent;

/**
 * @brief Defines a coasting axis event, which supports listening for the decaying sliding process generated by a
 * two-finger swipe on the touchpad. It is suitable for handling the inertial scrolling effect after a regular
 * axis event.
 *
 * When the user performs a two-finger swipe on the touchpad, the system constructs a coasting axis event based
 * on the finger lift speed, following the system-preset decaying curve. You can listen for this type of event to
 * handle the inertial scrolling effect immediately after a regular axis event.
 *
 * You can receive this event only when the following conditions are met: The user performs a two-finger swipe
 * on the touchpad, and a component registered for the {@link NODE_ON_COASTING_AXIS_EVENT} event via
 * {@link registerNodeEvent} exists at the pointer position. When this event is no longer needed, unregister the
 * event listener through {@link unregisterNodeEvent} to prevent the callback from being triggered continuously.
 *
 * @since 22
 */
typedef struct ArkUI_CoastingAxisEvent ArkUI_CoastingAxisEvent;

/**
 * @brief Defines touch test information, which is used to set the hit test policy and the child components to
 * which the result applies, and to obtain the touch test result of each child component.
 *
 * You can obtain this touch test information struct in the event callback only after registering the
 * {@link NODE_ON_CHILD_TOUCH_TEST} event through {@link registerNodeEvent}.
 *
 * This struct supports setting the touch test policy (for the value selection principle, see
 * {@link ArkUI_TouchTestStrategy}) and the ID of the child component to which the hit test applies, and
 * obtaining the touch test information item array that contains the detailed test result of each child
 * component.
 *
 * @since 22
 */
typedef struct ArkUI_TouchTestInfo ArkUI_TouchTestInfo;

/**
 * @brief Defines a touch test information item. A touch test is a hit test process that determines the target
 * component based on touch event coordinates. The touch test information item can be obtained in the event
 * callback only when you register the {@link NODE_ON_CHILD_TOUCH_TEST} event through {@link registerNodeEvent}.
 * This information item contains the information about child components in the touch test, and is applicable to
 * scenarios where child component information needs to be obtained and identified. You can use the
 * {@link OH_ArkUI_TouchTestInfoItem_GetXXX} series APIs to obtain the information and process the touch test
 * result.
 *
 * @since 22
 */
typedef struct ArkUI_TouchTestInfoItem ArkUI_TouchTestInfoItem;

/**
 * @brief Defines a touch test information item handle, which represents information such as the coordinates,
 * region, and component ID of a child component during a touch test. For details about the touch test APIs,
 * see ui_input_event.h.
 *
 * @since 22
 */
typedef ArkUI_TouchTestInfoItem* ArkUI_TouchTestInfoItemHandle;

/**
 * @brief Defines a handle array of touch test information items, which aggregates the information item handles
 * generated during touch hit testing for batch access to touch test information. For details about the APIs,
 * see native_gesture.h.
 *
 * @since 22
 */
typedef ArkUI_TouchTestInfoItemHandle* ArkUI_TouchTestInfoItemArray;

